# Operators Practice

a = 10
b = 5

# Arithmetic Operators
print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)

# Comparison Operators
print("Greater:", a > b)
print("Equal:", a == b)

# Logical Operators
print("Logical AND:", a > 5 and b < 10)
